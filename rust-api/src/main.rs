use axum::routing::get;
use axum::Json;
use std::path::PathBuf;
use std::sync::Arc;
use tokio_cron_scheduler::{Job, JobScheduler};
use tower_http::cors::{Any, CorsLayer};
use tracing::{error, info, Level};

mod config;
mod database;
mod error;
mod models;
mod procedures;
mod services;
mod utils;

use config::Config;
use database::DatabasePool;
use procedures::{mount, Ctx};
use services::PlatformPricingService;

#[tokio::main]
async fn main() -> anyhow::Result<()> {
    // Initialize tracing
    tracing_subscriber::fmt()
        .with_max_level(Level::INFO)
        .init();

    info!("Starting Kronova ROI Calculator API v{}", env!("CARGO_PKG_VERSION"));

    // Load configuration
    dotenv::dotenv().ok();
    let config = Arc::new(Config::from_env()?);

    // Initialize database pool
    let db = DatabasePool::new(&config.database_url).await?;

    // Run migrations
    // sqlx::migrate!("./migrations")
    //    .run(db.pool())
    //    .await?;

    // info!("Database migrations completed");

    // =========================================================================
    // rspc 0.4 Router Setup
    // =========================================================================

    // 1. Build the rspc router (procedures + types)
    let router = mount();
    let (procedures, types) = router.build().unwrap();

    // 2. Export TypeScript bindings for the frontend
    if let Err(e) = rspc::Typescript::default()
        .header("// Auto-generated by rspc - DO NOT EDIT")
        .export_to(
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../bindings.ts"),
            &types,
        )
    {
        tracing::warn!("Failed to export TypeScript bindings: {}", e);
    } else {
        info!("TypeScript bindings exported to ../bindings.ts");
    }

    // =========================================================================
    // Axum Application
    // =========================================================================

    // Configure CORS
    let cors = CorsLayer::new()
        .allow_origin(Any)
        .allow_methods(Any)
        .allow_headers(Any);

    // Clone db/config for the context factory closure
    let ctx_db = db.clone();
    let ctx_config = config.clone();

    // Build the axum application with rspc_axum integration
    let app = axum::Router::new()
        .route("/health", get(health_check))
        .nest(
            "/rspc",
            rspc_axum::endpoint(procedures, move |_parts: axum::http::request::Parts| {
                Ctx {
                    db: ctx_db.clone(),
                    config: ctx_config.clone(),
                }
            }),
        )
        .layer(cors);

    // =========================================================================
    // Hourly pricing refresh cron (every hour at :00)
    // =========================================================================
    let cron_db = db.clone();
    let cron_config = config.clone();

    tokio::spawn(async move {
        match JobScheduler::new().await {
            Ok(scheduler) => {
                let job = Job::new_async("0 0 * * * *", move |_uuid, _lock| {
                    let db = cron_db.clone();
                    let cfg = cron_config.clone();
                    Box::pin(async move {
                        let svc = PlatformPricingService::new(db, cfg);
                        if let Err(e) = svc.refresh_live_pricing().await {
                            error!("Pricing refresh cron failed: {}", e);
                        }
                    })
                });
                match job {
                    Ok(j) => {
                        if let Err(e) = scheduler.add(j).await {
                            error!("Failed to schedule pricing refresh job: {}", e);
                        }
                        if let Err(e) = scheduler.start().await {
                            error!("Failed to start scheduler: {}", e);
                        } else {
                            info!("Hourly pricing refresh cron scheduled");
                        }
                    }
                    Err(e) => error!("Failed to create cron job: {}", e),
                }
            }
            Err(e) => error!("Failed to initialise job scheduler: {}", e),
        }
    });

    let addr = format!("{}:{}", config.host, config.port);
    info!("Server listening on http://{}", addr);
    info!("rspc endpoint available at http://{}/rspc", addr);

    let listener = tokio::net::TcpListener::bind(&addr).await?;
    axum::serve(listener, app).await?;

    Ok(())
}

/// Simple health check endpoint (not part of rspc).
async fn health_check() -> Json<serde_json::Value> {
    Json(serde_json::json!({
        "status": "healthy",
        "service": "kronova-roi-api",
        "version": env!("CARGO_PKG_VERSION")
    }))
}
